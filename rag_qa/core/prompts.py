# -*- coding: utf-8 -*-
"""
rag_qa/core/prompts.py —— 所有提示词模板集中管理
================================================================

【为什么要把提示词单独放一个文件？】
   提示词（Prompt）是"写给大模型的说明书"，很大程度决定回答质量。
   集中管理的好处：
     1. 改提示词不用翻遍代码；
     2. 方便版本对比、A/B 测试；
     3. 团队成员共享同一套标准表达。

【技术：LangChain PromptTemplate】
   它是"带占位符的字符串模板"：
       t = PromptTemplate(template="问题:{q}", input_variables=["q"])
       t.format(q="你好")   →  "问题:你好"
   比 Python f-string 强在哪？
     - 支持传入任意值/批处理/复用（能直接接进 LangChain 的链）；
     - 格式统一，便于和 LLM、输出解析器拼接。

【本文件包含 4 个模板，对应链路的 4 个位置】
   1. rag_prompt            —— 最终回答生成（检索结果 + 历史 + 问题 → 答案）
   2. strategy_select_prompt—— 检索策略选择（直接/子查询/HyDE）
   3. hyde_prompt           —— HyDE：先生成"假设答案"再去检索
   4. subquery_prompt       —— 复杂问题拆成多个子问题
"""
from langchain_core.prompts import PromptTemplate


class RAGPrompts:
    """RAG 系统提示词模板集合（全是静态方法，直接 RAGPrompts.xxx() 调用）。"""

    @staticmethod
    def rag_prompt():
        """
        【核心模板】最终回答生成。
        输入变量：
            history —— 最近几轮对话（多轮记忆）
            context —— 检索到的知识库内容（父块拼接）
            question—— 用户当前问题
            phone   —— 人工客服电话（信息不足时兜底话术）
        """
        return PromptTemplate(
            template="""
    你是一个智能助手，负责帮助用户回答问题。请按照以下步骤处理：

    1. **分析问题和上下文**：
       - 基于提供的上下文（如果有）和你的知识回答问题。
       - 如果答案来源于检索到的文档，请在回答中明确说明，例如：“根据提供的文档，……”。

    2. **评估对话历史**：
       - 检查对话历史是否与当前问题相关（例如，是否涉及相同的话题、实体或问题背景）。
       - 如果对话历史与问题相关，请结合历史信息生成更准确的回答。
       - 如果对话历史无关（例如，仅包含问候或不相关的内容），忽略历史，仅基于上下文和问题回答。

    3. **生成回答**：
       - 提供清晰、准确的回答，避免无关信息。
       - 如果上下文和历史消息均不足以回答问题，请回复：“信息不足，无法回答，请联系人工客服，电话：{phone}。”

    **对话历史**:
    {history}

    **上下文**: 
    {context}

    **问题**: 
    {question}
    **回答**:
    """,
            # 声明模板里用到的占位符（LangChain 会校验 format 时是否都填了）
            input_variables=["context", "history", "question", "phone"],
        )

    @staticmethod
    def strategy_select_prompt():
        """
        【路由模板】让大模型从三种检索策略里选一个。
        只输出策略名（直接检索 / 子查询检索 / 假设问题检索），
        程序后面靠字符串精确匹配分支（strategy == "子查询检索"）。
        输入变量：query —— 用户问题
        """
        return PromptTemplate(
            template="""
你是检索策略选择专家，请根据用户问题的复杂程度，从以下三种策略中选择最合适的一种：

1. **直接检索**：问题简单、意图明确、关键词清晰，直接向量检索即可。
2. **子查询检索**：问题复杂、包含多个子问题或多个主题，需要拆分成多个子问题分别检索。
3. **假设问题检索**：问题语义模糊、表述口语化、关键词缺失，需要先假设生成答案再检索。

只输出策略名称，不要输出任何其他内容。

**用户问题**：
{query}

**选择的策略**：
""",
            input_variables=["query"],
        )

    @staticmethod
    def hyde_prompt():
        """
        【HyDE 模板】HyDE = Hypothetical Document Embeddings。
        原理：用户问题往往口语化、关键词少，向量和文档差得远；
        先让大模型"编一段假设答案"（像文档一样的书面语），
        再用这段假设答案去检索 —— 它和真实文档的语义更接近，命中率更高。
        输入变量：query —— 用户问题
        """
        return PromptTemplate(
            template="""
你是文档检索辅助专家。请根据用户问题，假设你已经知道了答案，写出一段假设性的答案文档。

要求：
1. 假设答案要尽量贴合问题的主题和关键词，涵盖可能出现的专业术语和概念。
2. 答案要具体、充实，像一段真实的文档内容，而不是简单的一句话。
3. 不要编造事实性错误内容，用常识合理推断。

**用户问题**：
{query}

**假设答案文档**：
""",
            input_variables=["query"],
        )

    @staticmethod
    def subquery_prompt():
        """
        【子查询模板】把"一个大问题"拆成"多个可检索的小问题"。
        要求每个子问题单独一行 → 程序按 "\n" 拆成列表分别去检索，最后合并去重。
        输入变量：query —— 用户问题
        """
        return PromptTemplate(
            template="""
你是问题拆分专家。请将下面的复杂问题拆分成多个独立、具体、可检索的子问题。

要求：
1. 每个子问题单独一行输出，不要编号，不要多余解释。
2. 每个子问题只聚焦一个主题，确保单独检索就能获得有效结果。
3. 拆分后的子问题合起来应覆盖原问题的所有方面。

**原始问题**：
{query}

**拆分后的子问题**：
""",
            input_variables=["query"],
        )
